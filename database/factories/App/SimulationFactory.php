	namespace Database\Factories\App;

	// App
	use Database\Factories\BaseFactory;
	use App\Models\App\Project;
	use App\Models\App\Simulation;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	CLASS CONSTRUCT
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


class SimulationFactory extends BaseFactory
{

	protected $model = Simulation::class;


	public function definition(): array {

		$project = Project::first();
		if (!$project) { $project = Project::factory()->create(); }

		return array_merge($this->getBaseProps(), [

			// simulation properties
			'model' =>	"heatmap",
			'params' => "{}",
			'status' =>	"waiting",
			'project_id' => $project->id,
		]);
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


}	// end class



