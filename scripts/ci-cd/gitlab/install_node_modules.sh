#!/bin/bash

#///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#/
#/	HELPER
#/
#///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	function removeLineInFile() {

		local filePath="$1"
		local search="$2"

		# escape "(" and ")" char
		search="$(sed -E 's/\(/\\(/g' <<<$search)"
		search="$(sed -E 's/\)/\\)/g' <<<$search)"

		if [[ "$OSTYPE" == "darwin"* ]]; then
			#sed -i '' -E "/$search/d" $filePath
			perl -i -ne "print unless /$search/" $filePath
		else
			sed -i -E "/$search/d" $filePath
		fi
	}



#///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#/
#/	BUN INSTALL
#/
#///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	removeLineInFile "package.json" "\"cypress"
	removeLineInFile "package.json" "\"backstopjs"
	removeLineInFile "package.json" "\"vite-bundle-visualizer"
	removeLineInFile "package.json" "\"inquirer"
	npm i --package-lock-only

	if grep -q "^SENTRY_LARAVEL_DSN=$" .env; then
		removeLineInFile "package.json" "\"@sentry\/tracing"
	fi
	if grep -q "^REVERB_APP_KEY=$" .env; then
		removeLineInFile "package.json" "\"laravel-echo"
		removeLineInFile "package.json" "\"pusher-js"
	fi

	bun install

	# force rollup for MacOS gitlab runner
	wget https://registry.npmjs.org/@rollup/rollup-linux-arm64-musl/-/rollup-linux-arm64-musl-4.36.0.tgz
	mkdir -p node_modules/@rollup/rollup-linux-arm64-musl
	tar -xzf rollup-linux-arm64-musl-4.36.0.tgz -C node_modules/@rollup/rollup-linux-arm64-musl

	# force rollup for Linux gitlab runner
	wget https://registry.npmjs.org/@rollup/rollup-linux-x64-musl/-/rollup-linux-x64-musl-4.36.0.tgz
	mkdir -p node_modules/@rollup/rollup-linux-x64-musl
	tar -xzf rollup-linux-x64-musl-4.36.0.tgz -C node_modules/@rollup/rollup-linux-x64-musl



#///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#/
#/	CLEANUP NODE MODULES
#/
#///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	for package in $(find node_modules -maxdepth 1 -mindepth 1 -type d); do

		# remove development folder
		[ -d "$package/dev" ] && rm -rf "$package/dev"

		# remove unnecessary folder
		[ -d "$package/examples" ] && rm -rf "$package/examples"
		[ -d "$package/docs" ] && rm -rf "$package/docs"
		[ -d "$package/test" ] && rm -rf "$package/test"
		[ -d "$package/tests" ] && rm -rf "$package/tests"

		# remove unnecessary files
		[ -f "$package/Readme.md" ] && rm -f "$package/Readme.md"
		[ -f "$package/README.md" ] && rm -f "$package/README.md"
		[ -f "$package/README.md" ] && rm -f "$package/README.md"
		[ -f "$package/readme.md" ] && rm -f "$package/readme.md"
		[ -f "$package/CHANGELOG.md" ] && rm -f "$package/CHANGELOG.md"
		[ -f "$package/LICENSE.md" ] && rm -f "$package/LICENSE.md"
		[ -f "$package/LICENSE.txt" ] && rm -f "$package/LICENSE.txt"
		[ -f "$package/LICENSE" ] && rm -f "$package/LICENSE"
		[ -f "$package/HISTORY.md" ] && rm -f "$package/HISTORY.md"
		[ -f "$package/SECURITY.md" ] && rm -f "$package/SECURITY.md"
		[ -f "$package/CMakeLists.txt" ] && rm -f "$package/CMakeLists.txt"

		# remove source maps
		for file in $(find "$package" -type f -name "*.map"); do
			rm -f $file
		done

		# remove type definitions
		for file in $(find "$package" -type f -name "*.d.ts"); do
			rm -f $file
		done

	done



#///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
#/
#/	CLEANUP PACKAGES
#/
#///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	[ -d "node_modules/@ckeditor/build" ] && rm -rf "node_modules/ckeditor5/build"
	for package in $(find node_modules/@ckeditor -maxdepth 1 -mindepth 1 -type d); do

		[ -d "$package/src" ] && rm -rf "$package/src"
		[ -d "$package/build" ] && rm -rf "$package/build"
		[ -d "$package/dist/Readme.md" ] && rm -rf "$package/dist/Readme.md"
		[ -d "$package/dist/CHANGELOG.md" ] && rm -rf "$package/dist/CHANGELOG.md"

		# delete all translations from "ckeditor5-special-characters"
		if [ -d "$package/lang/translations" ]; then
			rm -rf $package/lang/translations
		fi
		if [ -d "$package/dist/translations" ]; then
			for file in $(find "$package/dist/translations" -type f -name "*.js"); do
				if [[ ! "$file" == *"de."* && ! "$file" == *"en."* ]]; then
					rm -f $file
				fi
			done
		fi
	done

	# cleanup ckeditor5
	[ -d "node_modules/ckeditor5/build" ] && rm -rf "node_modules/ckeditor5/build"
	for file in $(find node_modules/ckeditor5/dist/translations -type f -name "*.js"); do
		if [[ ! "$file" == *"de."* && ! "$file" == *"en."* ]]; then
			rm -f $file
		fi
	done


	# cleanup dashjs
	for file in $(find node_modules/dashjs/dist -type f -name "*debug*"); do
		rm -f $file
	done


	# cleanup @babel
	for package in $(find node_modules/@babel -maxdepth 1 -mindepth 1 -type d); do
		if [[ "$package" == *"plugin-"* ]]; then
			rm -rf $package
		fi
	done


	# cleanup other packages
	[ -d "node_modules/@mixmark-io/domino/test" ] && rm -rf "node_modules/@mixmark-io/domino/test"
	[ -d "node_modules/prettier" ] && rm -rf "node_modules/prettier"


