	namespace App\Helper;

	// App
	use App\Http\Controllers\App\Simulation\BaseSimulationController;
	use App\Http\Controllers\App\Simulation\UmepHeatIslandController;
	use App\Http\Controllers\App\Simulation\IsodistanceController;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  CLASS
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


class SimulationRegistry {

	private static $controllers = [];

	public static function initialize(): void {

		if (empty(self::$controllers)) {
			self::$controllers = [
				'umep:heat_island' => new UmepHeatIslandController(),
				'isodistance' => new IsodistanceController(),
			];
		}
	}

	public static function getAllControllers(): array {

		self::initialize();
		return self::$controllers;
	}

	public static function getController(string $model): ?BaseSimulationController {

		self::initialize();
		return self::$controllers[$model] ?? null;
	}

	public static function getSupportedModels(): array {

		self::initialize();
		return array_keys(self::$controllers);
	}



/*/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


}
