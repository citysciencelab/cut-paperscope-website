	namespace App\Models\App;

	// App
	use App\Models\BaseModel;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	CLASS CONSTRUCT
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


class Simulation extends BaseModel {

	// the attributes that are mass assignable.
	protected $childFillable = [
		'model', 'params', 'status', 'project_id'
	];

	protected $translateFillable = [

	];

	// properties for model features
	public static $useSlug = false;
	public static $usePublished = false;
	public static $useSearch = true;

	// cast properties to correct type
	protected $casts = [
		'scene' => 'array',
		'params' => 'array',
		'results' => 'array',
	];


	public function __construct(array $attributes = []) {

		parent::__construct($attributes);

		$this->mergeFillable($this->childFillable, $this->translateFillable);
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	RELATIONS
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	public function project() {

		return $this->getSingleRelation('App\Models\App\Project', 'project_id');
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


} // end class
