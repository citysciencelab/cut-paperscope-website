	namespace App\Jobs;

	// Laravel
	use Illuminate\Contracts\Queue\ShouldBeUnique;

	// App
	use App\Jobs\Base\BaseJob;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	CLASS DECLARATION
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


class RunSimulation extends BaseJob implements ShouldBeUnique
{


	public function uniqueId(): string {

		return 'run-simulation-' . $this->target->id;
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	HANDLE
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	public function handle(): void {

		parent::handle();

		// update simulation status
		if($this->target->status == 'running') { return; }
		$this->target->status = 'waiting';
		$this->target->save();

		// execute simulation
		$command = "docker run ";
		$command .= "-v ".storage_path('app/public/')."simulations:/app/storage ";
		$command .= "paperscope-simulation:latest ";
		$command .= "python3 -m paperscope_simulation " . $this->target->id;

		exec($command, $output, $return_var);
	}



/*/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


}
