	namespace App\Jobs\Simulation;

	// Laravel
	use Illuminate\Contracts\Queue\ShouldBeUnique;

	// App
	use App\Jobs\Base\BaseJob;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	CLASS DECLARATION
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


class UmepHeatmapSimulation extends BaseJob implements ShouldBeUnique
{


	public function uniqueId(): string {

		return 'run-simulation-' . $this->target->id;
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	HANDLE
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	public function handle(): void {

		parent::handle();

		// update simulation status
		if($this->target->status == 'running') { return; }
		$this->target->status = 'waiting';
		$this->target->save();

		// execute simulation
		$command = "docker exec paperscope-simulation python3 -m paperscope_simulation";
		$command .= " " . $this->target->id;
		$command .= " " . config('app.url');

		exec($command, $output, $return_var);
	}



/*/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


}
