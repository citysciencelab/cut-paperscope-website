	namespace App\Http\Requests\App;

	// App
	use App\Http\Requests\Model\BaseModelSaveRequest;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
// 	CLASS CONSTRUCT
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


class SimulationWmsRequest extends BaseModelSaveRequest {


	protected $target = "simulations";
	protected $targetClass = \App\Models\App\Simulation::class;

	public function authorize(): bool {

		return true;
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	PREPARE DATA
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	// Normalize input keys to lowercase
	// This is necessary because OpenLayers sends keys in uppercase (e.g., "BBOX", "WIDTH", "HEIGHT").
	protected function prepareForValidation(): void	{

		$normalized = [];
		foreach ($this->all() as $key => $value) {
			$lowerKey = strtolower($key);
			$normalized[$lowerKey] = $value;
		}
		$this->merge($normalized);
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	VALIDATE
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	public function rules(): array {

		return $this->translate([

			'width' => 'required|integer|min:1',
			'height' => 'required|integer|min:1',
			'bbox' => 'required|string',
			'layers' => 'required|string|uuid',
		]);
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	ERROR MESSAGES
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	// rename variables for form error messages
	public function attributes(): array {

		return [
			...parent::attributes(),
			//'start' => 	trans('Startdatum'),
		];
	}


	public function messages(): array {

		return [
			...parent::messages(),
		];
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


} // end class
