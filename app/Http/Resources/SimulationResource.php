	namespace App\Http\Resources;

	// Laravel
	use Illuminate\Http\Request;

	// App
	use App\Http\Resources\Base\BaseModelResource;
	use App\Http\Resources\ProjectResource;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	CLASS
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


class SimulationResource extends BaseModelResource {


	public function getProps(Request $request): array {

		return [

			// simulation properties
			'name' =>		$this->name,
			'model' =>		$this->model,
			'params' =>		$this->params,
			'status' =>		$this->status,
			'project' =>	$this->getSingleRelation(ProjectResource::class, 'project'),

			// backend properties
			//$this->addBackendProperties(['approved' => $this->approved]),
		];
	}



/*/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


}
