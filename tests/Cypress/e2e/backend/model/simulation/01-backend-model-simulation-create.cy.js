describe('Create Simulation model in backend', () => {



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	CREATE SIMULATION
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	it('create with correct data', () => {

		const random = Math.random().toString(36).substring(7);

		// arrange: got to edit simulation
		cy.backendLogin();
		cy.visit('/backend/simulation/edit');
		cy.wait(2000);

		// act
		cy.get('#input-name').type('Cypress Test-Simulation ' + random);
		cy.get('#input-published-start').click();
		cy.wait(1000); // popup opening
		cy.get('.date-calendar-day.today').first().click();
		cy.get('.date-selector-confirm').click();
		cy.wait(1000); // popup closing
		cy.get('#input-public-0').check({force:true});
		// simulation properties
		cy.get('#input-type').type("Iusto fuga.");
		cy.get('#input-params').type("Et hic quasi unde.");
		cy.get('#input-status').type("Aut.");
		cy.get('.btn-model-confirm').click();

		// assert: simulation in list
		cy.url().should('include', '/backend/simulation');
		cy.get('.data-list-item[data-draggable] a').filter(':contains("Cypress Test-Simulation ' + random + '")').should('exist');
	});



/*/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


})
