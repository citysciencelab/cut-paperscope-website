describe('Delete Simulation model in backend', () => {



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	DELETE SIMULATION
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	it('delete from list', () => {

		// arrange: go to list page
		cy.backendLogin();
		cy.visit('/backend/simulation');
		cy.wait(2000);

		// arrange: find cypress test simulation
		var simulationName;
		var simulation = cy.get('.data-list-item[data-draggable] a').filter(':contains("Cypress Test-Simulation")').first();
		simulation.should(target => simulationName = target.text().trim());

		// click delete button
		simulation.parent().parent().find('.data-list-btn.delete').click();
		cy.wait(2000); // wait for async components

		// popup contains current name
		var popup = cy.get('.popup.modal');
		popup = popup.find('.modal-copy').should(target => {
			expect(target).to.contain(simulationName);
		});

		// confirm delete
		cy.get('.popup.modal').find('.btn-confirm').click();

		// assert simulation missing in list
		cy.wait(2000); // wait for list to update
		cy.get('.data-list-item[data-draggable] a').then(e => cy.get(e).filter(':contains("'+simulationName+' - edited")').should('not.exist'));
	});



/*/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


})
