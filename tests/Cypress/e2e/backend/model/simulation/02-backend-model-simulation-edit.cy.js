describe('Edit Simulation model in backend', () => {



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	EDIT SIMULATION
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	it('overwrite name', () => {

		// arrange: got to list page
		cy.backendLogin();
		cy.visit('/backend/simulation');
		cy.wait(2000);

		// arrange: find cypress test simulation
		var simulationName;
		var simulation = cy.get('.data-list-item[data-draggable] a').filter(':contains("Cypress Test-Simulation")').first();
		simulation.should(target => simulationName = target.text().trim().replace(' - edited',''));
		simulation.click();
		cy.wait(2000);

		// act
		cy.get('#input-name').then(el => cy.get(el).clear().type(simulationName + ' - edited'));
		cy.get('.btn-model-confirm').click();

		// assert
		cy.url().should('include', '/backend/simulation');
		cy.get('.data-list-item[data-draggable] a').then(e => cy.get(e).filter(':contains("'+simulationName+' - edited")').should('exist'));
	});



/*/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


})
