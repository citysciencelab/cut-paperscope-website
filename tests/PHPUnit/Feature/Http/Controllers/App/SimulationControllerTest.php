	namespace Tests\PHPUnit\Feature\Http\Controllers\App;

	// Laravel
	use Tests\PHPUnit\TestCase;
	use Illuminate\Foundation\Testing\RefreshDatabase;

	// App
	use App\Models\App\Simulation;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//    CLASS DECLARATION
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


class SimulationControllerTest extends TestCase {

	use RefreshDatabase;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//	MODEL GET
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	public function test_get_public() {

		// arrange
		$simulation = Simulation::factory()->public()->create();

		// act
		$data = $this->getData('/api/simulation/'.$simulation->id);

		// assert: check response is simulation model
		$this->assertEquals('simulation',$data['type']);
	}


	public function test_get_public_not_found() {

		$this->getError('/api/simulation/3ec9fc3b-a102-40b6-bd61-743f8bd2403b');
	}



