	namespace Tests\PHPUnit\Feature\Http\Requests\Backend;

	// Laravel
	use Tests\PHPUnit\TestCase;
	use Illuminate\Foundation\Testing\RefreshDatabase;
	use Illuminate\Support\Facades\Bus;

	// App
	use App\Jobs\ProcessSimulationUpload;
	use App\Models\App\Project;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//    CLASS DECLARATION
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


class SimulationSaveRequestTest extends TestCase {

	use RefreshDatabase;



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//    SAVE
//
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */


	public function test_save_simulation() {

		// arrange
		Bus::fake();
		$this->loginAsEditor();
		$project = Project::factory()->create();

		// arrange: form data
		$formData = $this->getBaseFormData();
		$formData['model'] = 'heatmap';
		$formData['params'] = '{}';
		$formData['status'] = 'waiting';
		$formData['project_id'] = $project->id;

		// act
		$simulation = $this->postData('/api/backend/simulation/save', $formData, $this->getBackendHeaders());

		// assert
		unset($formData['project_id']);
		$this->assertEquals('simulation',$simulation['type']);
		$this->assertArraySubset($formData, $simulation);

		// assert: jobs
		Bus::assertDispatched(ProcessSimulationUpload::class);
	}


	private function getBaseFormData() {

		return [
			'name' => 'test name',
			'public' => true,
			'order' => 0,
		];
	}



/*///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */

} // end class

